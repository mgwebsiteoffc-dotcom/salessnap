    <h2>Frequently Asked Questions &amp; Troubleshooting</h2>

    <div class="faq-item">
      <h4>How does the pre-change snapshot protection work?</h4>
      <p>Before SaleSnap applies any promotional discounts or changes to your products, it queries the Shopify Admin API to capture exact snapshots of variant prices, compare-at prices, tags, and descriptions. These snapshots are stored securely so you can roll back prices accurately when the sale ends.</p>
    </div>

    <div class="faq-item">
      <h4>What is "Conflict-Aware" price rollback?</h4>
      <p>If you or your team manually edit a product's price or description during an ongoing flash sale, SaleSnap detects the difference upon rollback instead of blindly overwriting your changes. The app flags the conflict and allows you to review the exact values in the Safety &amp; Audit tab.</p>
    </div>

    <div class="faq-item">
      <h4>How do theme copies and countdown announcement bars work?</h4>
      <p>SaleSnap creates a safe, isolated duplicate copy of your active theme with the countdown bar injected into <code>layout/theme.liquid</code>. You can customize headline text, timer expiration, and colors with live preview. If you want to return to your original setup, click "Restore Original Theme" to republish your unedited theme instantly.</p>
    </div>

    <div class="faq-item">
      <h4>How do I create Combo Bundles and Multi-Packs?</h4>
      <p>Go to the <strong>Products &amp; Bundles</strong> tab in the app. Select either "Create Combo Bundle" to bundle multiple distinct products together, or "Bulk Multi-Packs" to create 2-Packs, 3-Packs, or 5-Packs. Set your discount percentage or bundle price, and SaleSnap automatically generates the new bundle product in your Shopify catalog with customer savings calculated.</p>
    </div>

    <div class="faq-item">
      <h4>How do I upgrade, downgrade, or cancel my subscription?</h4>
      <p>Navigate to <strong>Billing &amp; Plans</strong> from the app menu. You can start a 7-day free trial of SaleSnap Pro with a single click. Upgrades and cancellations are billed securely via Shopify App Billing. If you cancel, your store immediately returns to the Free Tier.</p>
    </div>

    <h2>Step-by-Step User Guides</h2>

    <h3>1. Launching Your First Flash Sale</h3>
    <ol>
      <li>From the SaleSnap dashboard, click <strong>Create Campaign</strong>.</li>
      <li>Enter a campaign name and select products or collections to discount.</li>
      <li>Choose your discount percentage (e.g. 20% OFF) and optional promotional tags.</li>
      <li>Set the start and end dates/times in your store's timezone and click <strong>Review &amp; Schedule</strong>.</li>
      <li>SaleSnap will snapshot original data and execute the promotion on schedule.</li>
    </ol>

    <h3>2. Triggering an Emergency Restore</h3>
    <ol>
      <li>Go to the <strong>Campaigns</strong> or <strong>Overview</strong> tab.</li>
      <li>Click on the active campaign to open the Campaign Details modal.</li>
      <li>Click <strong>Rollback &amp; Restore Prices</strong> and confirm the prompt.</li>
      <li>SaleSnap immediately restores original variant prices and tags across all products.</li>
    </ol>

