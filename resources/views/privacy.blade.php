    <h2>1. Overview &amp; Scope</h2>
    <p>
      This Privacy Policy describes how SaleSnap ("we", "our", or "the App"), developed by RankBooster Infotech, collects, uses, stores, and protects information when installed by merchants on Shopify stores ("Store" or "Merchant").
    </p>

    <h2>2. Information We Collect</h2>
    <p>When you install and authorize SaleSnap, we receive access only to the specific technical information required to schedule promotions, create product bundles, and duplicate themes:</p>
    <ul>
      <li><strong>Shopify Store Metadata:</strong> Your myshopify.com store domain, primary store currency, store timezone, and installed app plan status.</li>
      <li><strong>OAuth Credentials:</strong> Encrypted Shopify API access tokens required to communicate securely with the Shopify Admin API on your behalf.</li>
      <li><strong>Product &amp; Variant Catalog Data:</strong> Product titles, variant IDs, SKU handles, price values, compare-at prices, product tags, collection assignments, and description HTML snippets.</li>
      <li><strong>Promotion Snapshots:</strong> Pre-change original prices, tags, and description prefixes captured immediately before a scheduled sale begins to facilitate conflict-aware price restoration.</li>
      <li><strong>Theme Identifiers:</strong> Store theme IDs and theme names needed to duplicate theme copies with synchronized countdown announcement bars.</li>
    </ul>

    <h2>3. How We Use Collected Information</h2>
    <p>We use the data collected strictly for the following functional purposes:</p>
    <ul>
      <li>To authenticate the merchant securely via Shopify App Bridge and session token verification.</li>
      <li>To apply scheduled percentage or fixed promotional price discounts, assign sale tags, and update description badges at specified dates and times.</li>
      <li>To create multi-product combo bundles and tiered bulk multi-packs in your Shopify product catalog.</li>
      <li>To generate theme copies embedded with customizable live countdown announcement bars.</li>
      <li>To safely restore product prices and tags back to their verified pre-sale state when a campaign ends or upon emergency rollback.</li>
      <li>To maintain audit event logs of scheduled changes and conflict reports.</li>
    </ul>

