    <h2>5. Data Retention &amp; Erasure</h2>
    <ul>
      <li><strong>Active Campaign Snapshots:</strong> Stored securely in database records for the active duration of the scheduled sale.</li>
      <li><strong>Completed / Cancelled Campaign Records:</strong> Retained for 90 days to provide historical audit logs and restore reporting, after which snapshots are automatically purged.</li>
      <li><strong>App Uninstallation:</strong> When you uninstall SaleSnap, Shopify sends an <code>app/uninstalled</code> webhook. Upon receipt, your store access tokens, settings, campaign snapshots, and logs are immediately and permanently deleted.</li>
    </ul>

    <h2>6. Mandatory GDPR &amp; Privacy Webhook Compliance</h2>
    <p>SaleSnap adheres strictly to Shopify's mandatory GDPR compliance endpoints:</p>
    <ul>
      <li><strong><code>customers/data_request</code>:</strong> Acknowledged with HTTP 200. SaleSnap does not store customer personal data.</li>
      <li><strong><code>customers/redact</code>:</strong> Acknowledged with HTTP 200. SaleSnap does not store customer personal data.</li>
      <li><strong><code>shop/redact</code>:</strong> Upon receiving this request, all store data, access tokens, and campaign records are permanently erased within 48 hours.</li>
    </ul>

    <h2>7. Security Safeguards</h2>
    <p>
      We implement industry-standard technical safeguards to protect your data. All communication between Shopify and our servers occurs exclusively over HTTPS/TLS encryption. Sensitive access tokens are encrypted at rest using AES-256 encryption. Our database servers are hosted in secure, isolated cloud infrastructure with automated backup safeguards.
    </p>

